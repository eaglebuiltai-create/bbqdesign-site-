/**
 * Generates the list of ZIP codes EagleBuilt will drive to.
 *
 * John's rule, 2026-11-26: "40 mile radius is good", plus "certain parts of
 * 530 foothills also". A 40-mile circle from the Granite Bay yard turns out to
 * cover nearly the whole foothills belt already - Auburn, Colfax, Grass Valley,
 * Penn Valley, Georgetown, Foresthill, Placerville, Camino, Dutch Flat, Alta,
 * Jackson - while dropping Vacaville, Stockton, Chico, Oroville, Truckee and
 * Tahoe. Two foothill towns fall just outside and are added by hand; see
 * EXCEPTIONS. Widening the circle to 45 miles would pull them in, but it also
 * drags in Lodi and half of Calaveras County, which is the wrong trade.
 *
 * Why a generated list rather than distance maths at run time: the answer only
 * changes when John changes his mind, the browser should not carry a table of
 * coordinates to re-derive a constant, and a plain list is something he can
 * read and argue with.
 *
 * Run it when the radius, the centre or the exceptions change:
 *
 *   curl -sSLO https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_zcta_national.zip
 *   unzip 2023_Gaz_zcta_national.zip
 *   node tools/build-service-area.mjs <path to 2023_Gaz_zcta_national.txt>
 *
 * It writes src/service-area.js and injects the same list into the designer
 * between the SERVICE-AREA markers. A test asserts the two copies agree, so a
 * hand-edit of either one fails the build rather than drifting quietly.
 */
import { readFileSync, writeFileSync } from "node:fs";

const CENTER = { zip: "95746", lat: 38.746924, lon: -121.166434, name: "Granite Bay" };
const MILES = 40;

/* ZIP areas out in the country are enormous, so the Census centroid sits well
   beyond the town itself. Both of these are nearer than the circle says. */
const EXCEPTIONS = {
  "95726": "Pollock Pines - 40.6mi by centroid, 0.6 over, Highway 50 past Placerville",
  "95959": "Nevada City - 44.7mi by centroid, but Grass Valley is in at 32 and they are 4 miles apart"
};

const GAZ = process.argv[2];
if (!GAZ) {
  console.error("usage: node tools/build-service-area.mjs <2023_Gaz_zcta_national.txt>");
  process.exit(1);
}

const R = 3958.7613;
const rad = (d) => (d * Math.PI) / 180;
function milesFromCenter(lat, lon) {
  const dLat = rad(lat - CENTER.lat);
  const dLon = rad(lon - CENTER.lon);
  const a = Math.sin(dLat / 2) ** 2 +
            Math.cos(rad(CENTER.lat)) * Math.cos(rad(lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

const zips = new Set(Object.keys(EXCEPTIONS));
for (const line of readFileSync(GAZ, "utf8").split(/\r?\n/).slice(1)) {
  if (!line.trim()) continue;
  const f = line.split("\t");
  const lat = parseFloat(f[5]);
  const lon = parseFloat(f[6]);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  if (milesFromCenter(lat, lon) <= MILES) zips.add(f[0].trim());
}
const list = [...zips].sort();

const header = [
  "/* GENERATED by tools/build-service-area.mjs - do not edit by hand.",
  " *",
  " * Every ZIP within " + MILES + " miles of the " + CENTER.name + " yard (" + CENTER.zip + "),",
  " * by Census ZCTA centroid, plus " + Object.keys(EXCEPTIONS).length + " added by hand:",
  ...Object.entries(EXCEPTIONS).map(([z, why]) => " *   " + z + "  " + why),
  " *",
  " * " + list.length + " ZIPs. Source: 2023 Census ZCTA gazetteer.",
  " * Regenerate with the command in the tool's own header. */"
].join("\n");

/* Eight per line: short enough to read, few enough lines to scroll past. */
const rows = [];
for (let i = 0; i < list.length; i += 8) {
  rows.push('  "' + list.slice(i, i + 8).join('", "') + '",');
}
const arrayLiteral = "[\n" + rows.join("\n").replace(/,$/, "") + "\n]";

writeFileSync("src/service-area.js", header + "\n\nexport const SERVICE_ZIPS = new Set(" + arrayLiteral + ");\n\n" + `
/* What we can do for someone, from their ZIP.
 *
 *   build    inside the ${MILES}-mile circle - we design it and we build it
 *   design   elsewhere in Northern California - we will draw it, someone else
 *            builds it. ZIP3 940-961 is the Bay Area, the Sacramento valley,
 *            the north coast and the far north. Fresno and south read as
 *            "tool": they are Central and Southern California.
 *   tool     anywhere else - the designer is free, take the budget to a
 *            contractor near you
 *   unknown  no ZIP we can read, so we claim nothing
 *
 * Five or nine digits only. A phone number typed into the ZIP field has ten,
 * and its first three are often an area code that would read as a real place,
 * so length is checked before anything else. */
export function areaFromZip(zip) {
  const z = String(zip == null ? "" : zip).replace(/[^0-9]/g, "");
  if (z.length !== 5 && z.length !== 9) return "unknown";
  const five = z.slice(0, 5);
  if (SERVICE_ZIPS.has(five)) return "build";
  const n = parseInt(five.slice(0, 3), 10);
  if (!Number.isFinite(n)) return "unknown";
  /* 952 and 953 are Stockton, Lodi, Manteca, Tracy and Modesto: the northern
     San Joaquin valley, which is south of here rather than Northern
     California. The four 952 ZIPs inside the circle are unaffected, because
     the service list above is tested first. */
  if (n === 952 || n === 953) return "tool";
  return (n >= 940 && n <= 961) ? "design" : "tool";
}

/* What the CRM inbox shows. Area first, so sorting by source groups them and
 * the label survives the column's length cap. */
export const AREA_LABEL = {
  build:  "service area",
  design: "design only",
  tool:   "out of area"
};

/* The source string a lead is filed under, with its area on the front.
 * Area first so sorting by source groups the local ones, and so the label
 * survives the CRM's 100-character cap: a truncated funnel name is still
 * readable, a truncated label is not. An unreadable ZIP leaves the source
 * exactly as it came - a row that says nothing about area is clearer than
 * one that says "unknown".
 *
 * Both the live /api/leads route and the bbqdesign sync call this, so the
 * tag on a row never depends on which door the lead came through. */
export function taggedSource(source, zip) {
  const given = String(source == null ? "" : source)
    .replace(/[\\r\\n]+/g, " ").trim().slice(0, 100) || "designer";
  const label = AREA_LABEL[areaFromZip(zip)] || "";
  return label ? (label + " / " + given).slice(0, 100) : given;
}
`.trimStart());

/* And the same list into the designer, which is one self-contained file and
   cannot import. The test compares the two. */
const FILE = "site/design/app/index.html";
const html = readFileSync(FILE, "utf8");
const BEGIN = "/* SERVICE-AREA:BEGIN generated by tools/build-service-area.mjs - do not edit */";
const END = "/* SERVICE-AREA:END */";
const i = html.indexOf(BEGIN);
const j = html.indexOf(END);
if (i === -1 || j === -1) {
  console.error("markers not found in " + FILE + " - add them around the SERVICE_ZIPS set first");
  process.exit(1);
}
const eol = html.includes("\r\n") ? "\r\n" : "\n";
const block = BEGIN + eol +
  "const SERVICE_ZIPS = new Set(" + arrayLiteral.split("\n").join(eol) + ");" + eol;
writeFileSync(FILE, html.slice(0, i) + block + html.slice(j), "utf8");

console.log("service area: " + list.length + " ZIPs within " + MILES +
            " miles of " + CENTER.zip + ", plus " + Object.keys(EXCEPTIONS).length + " by hand");
console.log("wrote src/service-area.js and injected into " + FILE);
